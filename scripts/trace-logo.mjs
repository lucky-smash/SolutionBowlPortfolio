// Traces the official logo PNG (public/brand/solution-bowl-logo.png) into SVG paths, one per brand colour, so the
// mark can be drawn, masked and embossed at any size. The artwork itself is unchanged: this is the same mark, vectorised.
import sharp from 'sharp';
import potrace from 'potrace';
import fs from 'node:fs';

const SRC = 'public/brand/solution-bowl-logo.png';
const { data, info } = await sharp(SRC).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const { width: W, height: H } = info;

function mask(pred) {
  const out = Buffer.alloc(W * H);
  for (let i = 0; i < W * H; i++) {
    const r = data[i * 4], g = data[i * 4 + 1], b = data[i * 4 + 2], a = data[i * 4 + 3];
    out[i] = a > 110 && pred(r, g, b) ? 0 : 255; // potrace traces dark pixels
  }
  return sharp(out, { raw: { width: W, height: H, channels: 1 } }).png().toBuffer();
}
const isOrange = (r, g, b) => r > 190 && r - b > 110 && g < 200;
const isGrey = (r, g, b) => Math.abs(r - g) < 22 && Math.abs(g - b) < 22 && r > 70 && r < 190;

const trace = (buf) =>
  new Promise((res, rej) =>
    potrace.trace(buf, { turdSize: 30, optTolerance: 0.25, alphaMax: 1, threshold: 128 }, (err, svg) => (err ? rej(err) : res(svg.match(/ d="([^"]+)"/)[1]))),
  );
const [orange, grey] = await Promise.all([trace(await mask(isOrange)), trace(await mask(isGrey))]);

// Symbol bounds: everything above the wordmark. Find the gap row between symbol and wordmark.
let gapTop = 0;
for (let y = Math.floor(H * 0.6); y < H; y++) {
  let any = false;
  for (let x = 0; x < W && !any; x++) if (data[(y * W + x) * 4 + 3] > 110) any = true;
  if (!any) { gapTop = y; break; }
}
fs.writeFileSync('src/components/brand/logo-paths.ts', `// Generated by scripts/trace-logo.mjs from ${SRC} (${W}×${H}). Do not edit.
export const LOGO_VIEWBOX = { width: ${W}, height: ${H}, symbolHeight: ${gapTop} };
export const LOGO_ORANGE = '${orange}';
export const LOGO_GREY = '${grey}';
`);
